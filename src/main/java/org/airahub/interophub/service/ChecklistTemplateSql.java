package org.airahub.interophub.service;

/**
 * Builds the seed INSERT statements for the draft checklist templates.
 * The Markdown files stay the source; this only quotes them for SQL.
 */
public final class ChecklistTemplateSql {

    private ChecklistTemplateSql() {
    }

    public static String generate(String initiativeMarkdown, String smallGroupMarkdown) {
        StringBuilder sql = new StringBuilder();
        sql.append("-- Generated by org.airahub.interophub.service.ChecklistTemplateSql\n");
        sql.append("-- from docs/initiatives/templates/initiative-checklist-v1.md and\n");
        sql.append("-- small-group-checklist-v1.md via ChecklistTemplateParser.\n");
        sql.append("-- Regenerate this block from those files instead of editing the item rows.\n");
        append(sql, initiativeMarkdown);
        append(sql, smallGroupMarkdown);
        return sql.toString();
    }

    private static void append(StringBuilder sql, String markdown) {
        ChecklistTemplateParser.Parsed parsed = ChecklistTemplateParser.parse(markdown);
        if (!parsed.ok()) {
            throw new IllegalArgumentException(parsed.errorText());
        }
        sql.append("INSERT INTO es_checklist_template\n");
        sql.append("  (template_kind, version_no, title, source_markdown, is_current, uploaded_by_user_id, uploaded_at)\n");
        sql.append("VALUES ('").append(parsed.kind()).append("', ").append(parsed.version()).append(", '")
                .append(escape(parsed.title())).append("', '").append(escape(markdown)).append("', 1, NULL, UTC_TIMESTAMP(6));\n");
        sql.append("SET @template_id = LAST_INSERT_ID();\n");
        for (ChecklistTemplateParser.Item item : parsed.items()) {
            sql.append("INSERT INTO es_checklist_template_item\n");
            sql.append("  (es_checklist_template_id, item_key, phase_label, title, guidance, due_anchor, due_offset_days, check_code, display_order)\n");
            sql.append("VALUES (@template_id, '").append(escape(item.key())).append("', '").append(escape(item.phase()))
                    .append("', '").append(escape(item.title())).append("', ").append(quote(item.guidance()))
                    .append(", ").append(quote(item.dueAnchor())).append(", ")
                    .append(item.dueOffsetDays() == null ? "NULL" : item.dueOffsetDays()).append(", ")
                    .append(quote(item.checkCode())).append(", ").append(item.displayOrder()).append(");\n");
        }
    }

    private static String quote(String value) {
        return value == null ? "NULL" : "'" + escape(value) + "'";
    }

    private static String escape(String value) {
        return value.replace("\\", "\\\\").replace("'", "''");
    }
}
